using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using Jellyfin.Plugin.PositionedSubtitles.Configuration;

namespace Jellyfin.Plugin.PositionedSubtitles.Services;

/// <summary>Builds styled ASS files from SRT using Jellyfin's ffmpeg (which keeps {\anN} as ASS overrides).</summary>
public static class AssBuilder
{
    public const string Marker = "; Generated by Jellyfin Positioned Subtitles plugin";
    private const string HashPrefix = "; PositionedSubtitles-Hash: ";

    public static readonly Regex PositionTag = new(@"\{\\an[1-9]\}", RegexOptions.Compiled);

    public static string BuildStyleLine(SubtitleStyle c)
    {
        var inv = CultureInfo.InvariantCulture;
        string font = string.IsNullOrWhiteSpace(c.FontName) ? "Arial" : c.FontName.Replace(",", string.Empty, StringComparison.Ordinal).Trim();

        // BorderStyle 3 = opaque box; libass draws it with OutlineColour, padded by Outline.
        int boxAlpha = 0xFF - (int)Math.Round(Math.Clamp(c.BackgroundOpacity, 0, 100) * 2.55);
        string outlineColour = c.Background ? ToAssColor(c.BackgroundColor, "#000000", boxAlpha) : ToAssColor(c.OutlineColor, "#000000", 0x00);
        double outline = c.Background ? Math.Max(Math.Clamp(c.Outline, 0, 20), 6) : Math.Clamp(c.Outline, 0, 20);

        return string.Join(',', new[]
        {
            "Style: Default",
            font,
            Math.Clamp(c.FontSize, 8, 400).ToString(inv),
            ToAssColor(c.PrimaryColor, "#FFFF00", 0x00),
            ToAssColor(c.PrimaryColor, "#FFFF00", 0x00),
            outlineColour,
            ToAssColor(c.ShadowColor, "#000000", 0x80),
            c.Bold ? "-1" : "0",
            "0", "0", "0", "100", "100", "0", "0",
            c.Background ? "3" : "1",
            outline.ToString(inv),
            Math.Clamp(c.Shadow, 0, 20).ToString(inv),
            "2", "80", "80",
            Math.Clamp(c.MarginV, 0, 500).ToString(inv),
            "1"
        });
    }

    /// <summary>#RRGGBB -> &amp;HAABBGGRR.</summary>
    public static string ToAssColor(string? html, string fallback, int alpha)
    {
        string v = (html ?? string.Empty).Trim().TrimStart('#');
        if (v.Length != 6 || !int.TryParse(v, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out _))
        {
            v = fallback.TrimStart('#');
        }

        string r = v.Substring(0, 2), g = v.Substring(2, 2), b = v.Substring(4, 2);
        return string.Create(CultureInfo.InvariantCulture, $"&H{alpha:X2}{b}{g}{r}").ToUpperInvariant();
    }

    public static string StyleHash(string styleLine)
    {
        byte[] hash = SHA256.HashData(Encoding.UTF8.GetBytes("v1|" + styleLine));
        return Convert.ToHexString(hash, 0, 8);
    }

    public static bool IsOwnFile(string path, out string? hash)
    {
        hash = null;
        try
        {
            using var reader = new StreamReader(path, Encoding.UTF8, true);
            for (int i = 0; i < 12; i++)
            {
                string? line = reader.ReadLine();
                if (line is null)
                {
                    break;
                }

                if (line.StartsWith(HashPrefix, StringComparison.Ordinal))
                {
                    hash = line.Substring(HashPrefix.Length).Trim();
                }
                else if (line.StartsWith(Marker, StringComparison.Ordinal))
                {
                    hash ??= string.Empty;
                }
            }
        }
        catch (IOException)
        {
            return false;
        }

        return hash is not null;
    }

    public static Task<string> ConvertAsync(string ffmpegPath, string srtPath, CancellationToken ct)
    {
        return RunFfmpegAsync(ffmpegPath, new[] { "-nostdin", "-hide_banner", "-v", "error", "-sub_charenc", "UTF-8", "-i", srtPath, "-f", "ass", "-" }, null, ct);
    }

    /// <summary>Converts SRT text (not a file) to ASS by piping it through ffmpeg.</summary>
    public static Task<string> ConvertTextAsync(string ffmpegPath, string srtText, CancellationToken ct)
    {
        return RunFfmpegAsync(ffmpegPath, new[] { "-hide_banner", "-v", "error", "-sub_charenc", "UTF-8", "-f", "srt", "-i", "pipe:0", "-f", "ass", "-" }, srtText, ct);
    }

    private static async Task<string> RunFfmpegAsync(string ffmpegPath, string[] args, string? stdinText, CancellationToken ct)
    {
        var psi = new ProcessStartInfo(ffmpegPath)
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            RedirectStandardInput = stdinText is not null,
            UseShellExecute = false,
            CreateNoWindow = true,
            StandardOutputEncoding = Encoding.UTF8,
            StandardErrorEncoding = Encoding.UTF8
        };
        if (stdinText is not null)
        {
            psi.StandardInputEncoding = new UTF8Encoding(false);
        }

        foreach (var a in args)
        {
            psi.ArgumentList.Add(a);
        }

        using var process = Process.Start(psi) ?? throw new InvalidOperationException("Could not start ffmpeg");
        if (stdinText is not null)
        {
            _ = Task.Run(async () =>
            {
                try
                {
                    await process.StandardInput.WriteAsync(stdinText).ConfigureAwait(false);
                    process.StandardInput.Close();
                }
                catch (IOException)
                {
                }
            });
        }

        Task<string> stdout = process.StandardOutput.ReadToEndAsync(ct);
        Task<string> stderr = process.StandardError.ReadToEndAsync(ct);
        using var timeout = CancellationTokenSource.CreateLinkedTokenSource(ct);
        timeout.CancelAfter(TimeSpan.FromMinutes(2));
        try
        {
            await process.WaitForExitAsync(timeout.Token).ConfigureAwait(false);
        }
        catch (OperationCanceledException)
        {
            try { process.Kill(true); } catch (InvalidOperationException) { }
            throw;
        }

        string output = await stdout.ConfigureAwait(false);
        string error = await stderr.ConfigureAwait(false);
        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException($"ffmpeg exited with {process.ExitCode}: {error.Trim()}");
        }

        return output;
    }

    /// <summary>Sets PlayRes 1920x1080, replaces the Default style and adds the ownership marker.</summary>
    public static string Patch(string ass, string styleLine, string hash)
    {
        var lines = ass.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
        var output = new List<string>(lines.Length + 3);
        bool styleReplaced = false;
        foreach (string line in lines)
        {
            if (line.StartsWith(Marker, StringComparison.Ordinal) || line.StartsWith(HashPrefix, StringComparison.Ordinal))
            {
                continue;
            }

            if (line.StartsWith("PlayResX:", StringComparison.Ordinal))
            {
                output.Add("PlayResX: 1920");
            }
            else if (line.StartsWith("PlayResY:", StringComparison.Ordinal))
            {
                output.Add("PlayResY: 1080");
            }
            else if (line.StartsWith("Style: Default,", StringComparison.Ordinal))
            {
                output.Add(styleLine);
                styleReplaced = true;
            }
            else
            {
                output.Add(line);
                if (line.Trim().Equals("[Script Info]", StringComparison.OrdinalIgnoreCase))
                {
                    output.Add(Marker);
                    output.Add(HashPrefix + hash);
                }
            }
        }

        if (!styleReplaced)
        {
            throw new InvalidOperationException("ffmpeg output has no Default style");
        }

        return string.Join('\n', output);
    }

    /// <summary>
    /// Recolours an existing ASS/SSA script: every style whose primary colour is white-ish gets
    /// <paramref name="primaryHtml"/>; everything else (fonts, sizes, positions, coloured signs,
    /// inline overrides) is kept. Returns the number of styles changed.
    /// </summary>
    public static string Restyle(string script, string primaryHtml, string hash, out int changedStyles)
    {
        changedStyles = 0;
        var lines = script.Replace("\r\n", "\n", StringComparison.Ordinal).TrimStart('﻿').Split('\n');
        var output = new List<string>(lines.Length + 2);
        int primaryIdx = -1, secondaryIdx = -1;
        bool inStyles = false;
        string newColor = ToAssColor(primaryHtml, "#FFFF00", 0x00);

        foreach (string raw in lines)
        {
            string line = raw;
            string trimmed = line.Trim();
            if (line.StartsWith(Marker, StringComparison.Ordinal) || line.StartsWith(HashPrefix, StringComparison.Ordinal))
            {
                continue;
            }

            if (trimmed.StartsWith('['))
            {
                inStyles = trimmed.Contains("Styles", StringComparison.OrdinalIgnoreCase);
            }
            else if (inStyles && trimmed.StartsWith("Format:", StringComparison.OrdinalIgnoreCase))
            {
                var cols = trimmed.Substring(7).Split(',').Select(c => c.Trim()).ToList();
                primaryIdx = cols.FindIndex(c => c.Equals("PrimaryColour", StringComparison.OrdinalIgnoreCase));
                secondaryIdx = cols.FindIndex(c => c.Equals("SecondaryColour", StringComparison.OrdinalIgnoreCase));
            }
            else if (inStyles && primaryIdx >= 0 && trimmed.StartsWith("Style:", StringComparison.OrdinalIgnoreCase))
            {
                int colon = line.IndexOf(':', StringComparison.Ordinal);
                var fields = line.Substring(colon + 1).Split(',');
                if (primaryIdx < fields.Length && TryParseAssColor(fields[primaryIdx], out uint primary) && IsWhitish(primary))
                {
                    string alpha = ((primary >> 24) & 0xFF).ToString("X2", CultureInfo.InvariantCulture);
                    string colour = "&H" + alpha + newColor.Substring(4);
                    if (secondaryIdx >= 0 && secondaryIdx < fields.Length && TryParseAssColor(fields[secondaryIdx], out uint secondary) && (secondary & 0xFFFFFF) == (primary & 0xFFFFFF))
                    {
                        fields[secondaryIdx] = colour;
                    }

                    string lead = fields[primaryIdx].Length - fields[primaryIdx].TrimStart().Length > 0 ? " " : string.Empty;
                    fields[primaryIdx] = lead + colour;
                    line = line.Substring(0, colon + 1) + string.Join(',', fields);
                    changedStyles++;
                }
            }

            output.Add(line);
            if (trimmed.Equals("[Script Info]", StringComparison.OrdinalIgnoreCase))
            {
                output.Add(Marker);
                output.Add(HashPrefix + hash);
            }
        }

        return string.Join('\n', output);
    }

    /// <summary>Parses &amp;HAABBGGRR / &amp;HBBGGRR (hex) or a decimal SSA colour into AABBGGRR.</summary>
    public static bool TryParseAssColor(string value, out uint color)
    {
        string v = value.Trim().TrimEnd('&');
        if (v.StartsWith("&H", StringComparison.OrdinalIgnoreCase))
        {
            return uint.TryParse(v.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out color);
        }

        if (long.TryParse(v, NumberStyles.Integer, CultureInfo.InvariantCulture, out long dec))
        {
            color = unchecked((uint)dec);
            return true;
        }

        color = 0;
        return false;
    }

    private static bool IsWhitish(uint abgr)
    {
        uint r = abgr & 0xFF, g = (abgr >> 8) & 0xFF, b = (abgr >> 16) & 0xFF;
        return r >= 0xD0 && g >= 0xD0 && b >= 0xD0;
    }

    public static int CountDialogues(string ass)
    {
        int n = 0;
        foreach (var line in ass.AsSpan().EnumerateLines())
        {
            if (line.StartsWith("Dialogue:", StringComparison.Ordinal))
            {
                n++;
            }
        }

        return n;
    }

    public static int CountSrtCues(string srt)
    {
        int n = 0;
        foreach (var line in srt.AsSpan().EnumerateLines())
        {
            if (line.Contains("-->", StringComparison.Ordinal))
            {
                n++;
            }
        }

        return n;
    }
}
